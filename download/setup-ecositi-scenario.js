// ─── MAX probe: клавиатура из 8 рядов (валидация лимитов) ───────────────────
async function probeMaxKeyboard(token) {
  const buttons = [];
  for (let i = 1; i <= 8; i++) {
    buttons.push([{ type: 'callback', text: `Кнопка ${i}`, payload: `p${i}` }]);
  }
  try {
    const res = await fetch('https://botapi.max.ru/messages?chat_id=1', {
      method: 'POST',
      headers: { Authorization: token, 'Content-Type': 'application/json' },
      body: JSON.stringify({ text: 'probe (не доставляется: chat_id=1)', attachments: [{ type: 'inline_keyboard', payload: { buttons } }] }),
      signal: AbortSignal.timeout(15000),
    });
    const json = await res.json().catch(() => null);
    const msg = json && typeof json === 'object' ? json.message ?? JSON.stringify(json).slice(0, 120) : 'нет json';
    console.log(`MAX probe 8-row keyboard → HTTP ${res.status}: ${msg}`);
    // chat.not.found = клавиатура принята валидацией, ошибка только по чату
    return { status: res.status, message: String(msg) };
  } catch (e) {
    console.log('MAX probe network error:', String(e));
    return { status: 0, message: String(e) };
  }
}

