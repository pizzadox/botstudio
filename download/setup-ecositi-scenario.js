const nodes = [];
const edges = [];
let eid = 0;
function N(id, type, x, y, data, label) {
  nodes.push({ id, type, position: { x, y }, data: { label, ...data } });
}
function E(source, target, handle) {
  edges.push({ id: `e${++eid}`, source, target, ...(handle ? { sourceHandle: handle } : {}) });
}
function BTN(id, text) { return { id, text }; }

