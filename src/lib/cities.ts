/**
 * Города обслуживания «Экосити» (Новгородская область).
 * Используются:
 *  - сценарием бота (кнопки выбора города перед адресом заявки);
 *  - формой создания заявки оператором (раздел «Заявки» в ЛК);
 *  - геокодингом (город подставляется в адрес → точная точка на карте).
 *
 * Первые CITY_BUTTON_COUNT городов показываются кнопками в боте,
 * остальные доступны через «Другой город» (свободный ввод) и в ЛК.
 */

export const SERVICE_CITIES: string[] = [
  'Великий Новгород',
  'Боровичи',
  'Валдай',
  'Старая Русса',
  'Окуловка',
  'Чудово',
  'Сольцы',
  'Малая Вишера',
  'Крестцы',
  'Хвойная',
  'Пестово',
  'Демянск',
  'Любытино',
];

/** Кнопки выбора города в боте: первые N городов (лимит клавиатуры MAX — 8 рядов) */
export const CITY_BUTTON_COUNT = 5;

/** Города, показываемые кнопками в боте */
export function cityButtons(): string[] {
  return SERVICE_CITIES.slice(0, CITY_BUTTON_COUNT);
}

/** Полный адрес для геокодинга: «Город, улица, дом» */
export function composeAddress(city: string | null | undefined, street: string | null | undefined): string {
  const c = (city ?? '').trim();
  const s = (street ?? '').trim();
  if (c && s) return `${c}, ${s}`;
  return s || c;
}
